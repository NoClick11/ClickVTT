interface Entrada {
    nome: string;
    faccao: NpcModelo['faccao'];
    nd: string;
    xp: number;
    pp?: number;
    cr: number;
    /** `[médio, dados]` */
    pv: [number, string];
    bp: number;
    cd: number;
    desl: number;
    nado: number;
    /** FOR, DES, CON, SAB, PRE, VON */
    at: [number, number, number, number, number, number];
    pericias?: string;
    salv?: string;
    passiva: number;
    aspectos?: TextoNpc[];
    ataques?: AtaqueNpc[];
    multiplos?: [number, string];
    bonus?: TextoNpc[];
    reacoes?: TextoNpc[];
    tecnicas?: TecnicaNpc[];
    lendarias?: NpcModelo['lendarias'];
}

const slug = (s: string) =>
    s
        .normalize('NFD')
        .replace(/[̀-ͯ]/g, '')
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, '-')
        .replace(/^-|-$/g, '');

const npc = (e: Entrada): NpcModelo => {
    const [f, d, c, s, p, v] = e.at;
    const atributos: Record<AtributoNpc, number> = { for: f, des: d, con: c, sab: s, pre: p, von: v };

    return {
        id: `${slug(e.faccao)}-${slug(e.nome)}`,
        nome: e.nome,
        faccao: e.faccao,
        nd: e.nd,
        xp: e.xp,
        pp: e.pp ?? null,
        cr: e.cr,
        pv: { medio: e.pv[0], dados: e.pv[1] },
        bp: e.bp,
        cd: e.cd,
        deslocamento: e.desl,
        nado: e.nado,
        atributos,
        pericias: e.pericias ?? '',
        salvaguardas: e.salv ?? '',
        sentidos: `Percepção Passiva ${e.passiva}.`,
        aspectos: e.aspectos ?? [],
        ataques: e.ataques ?? [],
        ...(e.multiplos ? { multiplos: { n: e.multiplos[0], com: e.multiplos[1] } } : {}),
        acoesBonus: e.bonus ?? [],
        reacoes: e.reacoes ?? [],
        tecnicas: e.tecnicas ?? [],
        ...(e.lendarias ? { lendarias: e.lendarias } : {}),
    };
};

