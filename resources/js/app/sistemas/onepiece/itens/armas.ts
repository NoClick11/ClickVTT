import type { CategoriaId, DadosDeArmaDoCatalogo, ItemDoCatalogo } from './tipos.ts';

interface Opcoes {
    apelidos?: string[];
    equipavel?: boolean;
    unidade?: string;
    dados?: ItemDoCatalogo['dados'];
}

const arma = (
    id: string,
    nome: string,
    categoria: CategoriaId,
    preco: number | null,
    peso: number,
    descricao: string,
    a: DadosDeArmaDoCatalogo,
    o: Opcoes = {},
): ItemDoCatalogo => ({
    id,
    nome,
    ...(o.apelidos ? { apelidos: o.apelidos } : {}),
    categoria,
    tipo: 'item',
    // armas comuns: "facilmente encontradas na maioria das ilhas que possuem lojas especializadas"; as especiais também são comuns
    raridade: 'comum',
    preco,
    ...(o.unidade ? { unidade: o.unidade } : {}),
    peso,
    descricao,
    equipavel: o.equipavel ?? categoria !== 'municao',
    arma: a,
    ...(o.dados ? { dados: o.dados } : {}),
    loja: true,
});

